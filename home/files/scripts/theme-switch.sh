#!/bin/bash
set -euo pipefail

THEME="${1:-}"
THEMES_DIR="$HOME/.config/themes"
# ACTIVE_FILE is injected by the theme module (themes.activeFile); the theme
# definitions live next to it.
REPO_THEMES_DIR="$(dirname "$ACTIVE_FILE")/themes"
LINKS_FILE="$THEMES_DIR/links.sh"
LOCK_FILE="${XDG_RUNTIME_DIR:-/tmp}/theme-switch.lock"

exec 9>"$LOCK_FILE"
flock 9

list_themes() {
  find "$REPO_THEMES_DIR" -maxdepth 1 -type f -name '*.nix' -printf '%f\n' |
    sed 's/\.nix$//' |
    sort
}

# A theme is defined in the repo (so it can be selected for the next rebuild)…
theme_in_repo() {
  [[ -f "$REPO_THEMES_DIR/$1.nix" ]]
}

# …and is switchable at runtime only once Home Manager has generated its assets.
theme_built() {
  [[ -d "$THEMES_DIR/$1" && -f "$THEMES_DIR/$1/vars" ]]
}

# Get current theme from active.nix
if [[ -f $ACTIVE_FILE ]]; then
  CURRENT_THEME=$(grep -oP 'themes/\K[^.]+' "$ACTIVE_FILE" 2>/dev/null || echo "unknown")
else
  CURRENT_THEME="unknown"
fi

# List available themes if no argument
if [[ -z $THEME ]]; then
  echo "Available themes:"
  list_themes
  echo ""
  echo "Current theme: $CURRENT_THEME"
  echo ""
  echo "Usage: theme-switch <theme-name>"
  exit 0
fi

# Validate theme exists
if ! theme_in_repo "$THEME"; then
  echo "Error: Theme not found: $THEME"
  echo "Available themes:"
  list_themes
  exit 1
fi

# Assets are generated by Home Manager (home/theme/module.nix). A theme added to
# the repo but not yet built can't be switched to at runtime.
if ! theme_built "$THEME"; then
  echo "Error: Theme '$THEME' is defined but its assets aren't built yet."
  echo "Run 'rebuild' to generate them, then switch."
  exit 1
fi

# Check if already active
if [[ $CURRENT_THEME == "$THEME" ]]; then
  # Starting an already running unit does nothing.
  systemctl --user start wallpaper.service
  echo "Theme '$THEME' is already active"
  exit 0
fi

# Update active.nix
if [[ ! -f $ACTIVE_FILE ]]; then
  echo "Error: $ACTIVE_FILE not found"
  exit 1
fi

echo "import ./themes/$THEME.nix" >"$ACTIVE_FILE"
echo "Updated active.nix to $THEME"

# Reuse the generated symlink map from Home Manager to avoid duplicating paths.
if [[ ! -f $LINKS_FILE ]]; then
  echo "Error: $LINKS_FILE not found"
  exit 1
fi

# shellcheck source=/dev/null
source "$LINKS_FILE"
link_theme_assets "$THEMES_DIR/$THEME"

# Live-reload colors come straight from the Nix-generated vars file, so this
# script never re-parses theme .nix definitions (Nix is the single source).
# Declared here so their origin is unambiguous; the source below fills them in.
bg='' brown='' amber=''
# shellcheck source=/dev/null
source "$THEMES_DIR/$THEME/vars"

quiet-shell-ipc reloadTheme >/dev/null 2>&1 || true

# Reload apps
hyprctl eval "hl.config({general={col={active_border='rgb($amber)',inactive_border='rgb($brown)'}},decoration={shadow={color='rgba(${bg}cc)'}},misc={background_color='rgb($bg)'}})" >/dev/null

# Warm the kernel page cache so swaybg's decode is CPU-bound, not disk-bound:
# while the unit restarts, the theme's background colour shows instead.
cat "$HOME/.local/share/wallpapers/current.png" >/dev/null 2>&1 || true
systemctl --user restart wallpaper.service

ps -eo pid=,comm= |
  awk '$2 == ".kitty-wrapped" || $2 == "kitty" { print $1 }' |
  xargs -r kill -USR1 2>/dev/null || true

notify-send "Theme changed" "Switched to: $THEME" || true
echo "✓ Theme switched to $THEME"
